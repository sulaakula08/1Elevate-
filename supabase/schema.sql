-- --------------------------------------------------------- signup trigger --
-- A profile for every new signup, filled from whatever the sign-up form passed
-- as metadata. Without this a student authenticates successfully and then has
-- nowhere to store a target score.

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    coalesce(new.email, '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ------------------------------------------------------- making the owner --
-- Exactly one step is manual, and deliberately so: there is no way to become
-- the owner through the app, because the first owner is the thing every other
-- permission is derived from.
--
-- Sign up through the app normally, then run this once with your own address:
--
--   update public.profiles set role = 'owner' where email = 'you@example.com';
--
-- From then on everything else is done in the app: Admin → People lets you
-- appoint admins, who can write the shared question bank, and demote them
-- again. set_role() refuses to mint another owner, so a second owner is also a
-- SQL-editor job — worth doing for one trusted person, so a lost account does
-- not leave the project with nobody able to appoint anyone.
--
-- To audit who holds what, especially on a database that ran the version of
-- this file where a student could grant themselves admin:
--
--   select email, role from public.profiles where role <> 'student';

-- =========================================================== community ==
-- The feed: posts, reactions, comments and saves.
--
-- Everything a student writes is attributed to their auth id, never to a name
-- sent by the browser, so a post cannot be published under someone else's
-- identity no matter what the client sends.

-- ------------------------------------------------------- public profiles --
-- Names have to be visible to everyone or a feed is anonymous, but the
-- profiles table also holds email, grade and target score, and its read policy
-- correctly limits a student to their own row.
--
-- This view is the narrow window through it: id and display name, nothing else.
-- It is deliberately NOT security_invoker, so it runs as its owner and is not
-- blocked by that policy — which is safe precisely because the column list is
-- fixed here and cannot be widened by a caller.

create or replace view public.public_profiles as
  select
    id,
    -- Never expose the address. A student who set no name is shown the part
    -- before the @, which is what they would have been called anyway.
    coalesce(nullif(trim(name), ''), split_part(coalesce(email, ''), '@', 1), 'Student') as display_name,
    role
  from public.profiles;

revoke all on public.public_profiles from anon, public;
grant select on public.public_profiles to authenticated;

-- -------------------------------------------------------------- posts --

create table if not exists public.community_posts (
  id         uuid primary key default gen_random_uuid(),
  author_id  uuid not null references public.profiles (id) on delete cascade,
  -- 'post' is an ordinary user-authored post: words, and nothing structured.
  -- The other six are shapes the product understands — a question carries an
  -- answer pair, progress carries two scores — and five of them are on their way
  -- to being written by the app itself rather than by a person choosing a
  -- category from a list.
  type       text not null check (type in
               ('post', 'question', 'progress', 'achievement', 'explanation',
                'study-update', 'resource')),
  exam       text not null default 'sat',
  topic      text,
  text       text,
  -- The type-specific block, kept as jsonb for the same reason the question
  -- bank does: six post shapes would otherwise mean six sets of nullable
  -- columns, and a new post type would mean a migration.
  payload    jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- `create table if not exists` leaves an existing table's constraints alone, so
-- a project created before 'post' was a type still carries the six-value check
-- and would reject an ordinary post with a constraint violation. Replacing it
-- explicitly is what lets this file run against an existing project as well as
-- a fresh one — the same reason profiles_role_check is replaced above.
alter table public.community_posts drop constraint if exists community_posts_type_check;
alter table public.community_posts
  add constraint community_posts_type_check check (type in
    ('post', 'question', 'progress', 'achievement', 'explanation',
     'study-update', 'resource'));

create index if not exists community_posts_recent on public.community_posts (created_at desc);

-- Moderation, kept reversible. A hidden post is still a row: it leaves every
-- student's feed immediately, and an admin who hid the wrong thing can put it
-- back. Hard deletion stays the author's own choice, which is the one case where
-- the person asking is entitled to lose the data.
alter table public.community_posts
  add column if not exists hidden_at timestamptz,
  add column if not exists hidden_by uuid references public.profiles (id) on delete set null;

alter table public.community_posts enable row level security;

-- Hidden means hidden, in the database and not merely in the query the feed
-- happens to send. An admin still reads it, because the moderation queue has to
-- show what it is moderating.
drop policy if exists "posts: read signed in" on public.community_posts;
create policy "posts: read signed in"
  on public.community_posts for select to authenticated
  using (hidden_at is null or public.is_admin());

drop policy if exists "posts: insert own" on public.community_posts;
create policy "posts: insert own"
  on public.community_posts for insert
  with check (author_id = auth.uid());

drop policy if exists "posts: update own" on public.community_posts;
create policy "posts: update own"
  on public.community_posts for update
  using (author_id = auth.uid()) with check (author_id = auth.uid());

-- Authors can withdraw their own post; admins can remove anyone's, because a
-- feed with no moderation is a liability the moment it has real users.
drop policy if exists "posts: delete own or admin" on public.community_posts;
create policy "posts: delete own or admin"
  on public.community_posts for delete
  using (author_id = auth.uid() or public.is_admin());

-- The same trap the profiles table fell into, for the same reason: the update
-- policy above says WHICH ROW an author may write — their own — and says nothing
-- about which columns. `hidden_at` lives in that row, so under policies alone an
-- author whose post an admin had hidden could send
--
--   PATCH /rest/v1/community_posts?id=eq.<their own post>  {"hidden_at":null}
--
-- straight to PostgREST with the publishable key and put it back. That is a
-- moderation bypass, not a cosmetic problem.
--
-- Column privileges are checked independently of RLS, so revoking UPDATE and
-- granting it back on only the three columns a post's own words live in closes
-- it: hidden_at and hidden_by are not writable by anyone signed in, and the only
-- thing that sets them is the definer function below, which checks is_admin()
-- first. author_id is left out too, so a post cannot be reassigned.
revoke update on public.community_posts from anon, authenticated;
grant update (text, topic, payload) on public.community_posts to authenticated;

