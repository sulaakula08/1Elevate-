-- ------------------------------------------------------- reset statistics --
-- Wipes every student's practice history: attempts, mock results and the
-- community's derived counters stay out of it — this is progress data only.
--
-- A definer function rather than a delete policy, for the same reason set_role()
-- is one. There is no delete policy on attempts or mocks anywhere in this file,
-- and that is deliberate: an append-only log cannot lose a row to a bug. This is
-- the single, named exception, and it checks the caller is the owner before it
-- touches anything.
--
-- Accounts are not touched. Signups are the one figure that must survive a
-- reset, because it is the only record of who ever joined.

create or replace function public.reset_statistics()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  removed_attempts bigint;
  removed_mocks bigint;
begin
  if not public.is_owner() then
    raise exception 'Only the owner can reset statistics' using errcode = '42501';
  end if;

  select count(*) into removed_attempts from public.attempts;
  select count(*) into removed_mocks from public.mocks;

  delete from public.attempts;
  delete from public.mocks;

  return json_build_object('attempts', removed_attempts, 'mocks', removed_mocks);
end;
$$;

revoke all on function public.reset_statistics() from public;
grant execute on function public.reset_statistics() to authenticated;

-- ==================================================== service sections ==
-- Lets the owner close part of the product while it is being worked on, so a
-- broken section shows a written explanation instead of a broken screen.
--
-- One row per section, created on demand — a missing row means open, so a
-- section nobody has ever touched needs no row and a new section added to the
-- app is open by default rather than invisible.

create table if not exists public.service_sections (
  -- The section's route key: community, practice, mock, review, progress.
  key        text primary key,
  closed     boolean not null default false,
  -- Shown to students in place of the section. Optional: there is a sensible
  -- default in the UI, and an owner closing something in a hurry should not
  -- have to write copy first.
  message    text,
  updated_by uuid references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now()
);

alter table public.service_sections enable row level security;

-- Everyone signed in reads it: the app has to know what is closed in order to
-- say so, and that is not privileged information.
drop policy if exists "sections: read signed in" on public.service_sections;
create policy "sections: read signed in"
  on public.service_sections for select to authenticated using (true);

-- Writing is the owner's alone. Not is_admin(): closing the product for every
-- student is a different kind of decision from writing a question, and the
-- people who do the latter should not be able to do the former by accident.
drop policy if exists "sections: write owner" on public.service_sections;
create policy "sections: write owner"
  on public.service_sections for all
  using (public.is_owner())
  with check (public.is_owner());

-- ------------------------------------------------- question id integrity --
-- A blank id caused real data loss, so the database refuses one now rather than
-- trusting every client to.
--
-- What happened: the editor sends an empty id for a new question, an early
-- version of the API looked that empty value up among existing rows, and from
-- then on every save matched the blank row, was treated as an edit, and
-- overwrote it. Two admins writing to different sections ended up with one
-- question between them.
--
-- The delete runs first, because the constraint cannot be added while a row
-- violates it. It removes at most the single blank row; on a clean table it
-- matches nothing, which keeps this file re-runnable.

delete from public.custom_questions where trim(coalesce(id, '')) = '';

alter table public.custom_questions drop constraint if exists custom_questions_id_present;
alter table public.custom_questions
  add constraint custom_questions_id_present check (length(trim(id)) > 0);

