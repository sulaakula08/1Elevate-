/** Base dictionary plus the per-area fragments in `lib/copy`. */
const STRINGS: Dict = { ...D, ...COPY };

type Ctx = {
  /** UI string by key. */
  t: (key: string) => string;
  /** Content text from the item bank. */
  tx: (text: LocalizedText | undefined) => string;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  // One language means no post-mount adoption, and therefore no hydration
  // mismatch and no flash of the wrong copy on first paint.
  const t = useCallback((key: string) => STRINGS[key]?.en ?? key, []);
  const tx = useCallback((text: LocalizedText | undefined) => text?.en ?? "", []);

  return <I18nContext.Provider value={{ t, tx }}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside <I18nProvider>");
  return ctx;
}
